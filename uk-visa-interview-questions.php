                <div class="svc-lede" style="text-align:left;max-width:900px;">
                    <h3>Is An Interview Actually Required?</h3>
                    <p>For most Standard Visitor visa applications, there is no interview by default. UKVI primarily assesses your application on the documents submitted. A follow-up call or request for more information is more the exception than the rule &mdash; but it does happen, especially where an application's financial picture, travel history, or ties to India need clarifying.</p>

                    <h3>What Follow-Up Questions Typically Cover</h3>
                    <ul>
                        <li><strong>Purpose of visit</strong> &mdash; a clear, consistent account of why you're travelling and what you'll be doing, matching your covering letter and itinerary.</li>
                        <li><strong>Ties to India</strong> &mdash; your job, business, property or family situation, and why you're expected to return after your visit.</li>
                        <li><strong>Financial standing</strong> &mdash; who is funding the trip, and whether your bank statements support the trip's cost comfortably.</li>
                        <li><strong>Travel history</strong> &mdash; previous international trips and whether you complied with earlier visa conditions.</li>
                        <li><strong>Accommodation and itinerary details</strong> &mdash; where you're staying, and whether your plans are specific rather than vague.</li>
                    </ul>

                    <h3>How To Prepare</h3>
                    <ul>
                        <li>Know your own application. Be able to explain every document you submitted, in your own words, without hesitation.</li>
                        <li>Keep your story consistent across your covering letter, itinerary and any answers you give &mdash; inconsistency is one of the more common reasons an officer asks further questions.</li>
                        <li>Have a clear, honest answer for "why will you return to India?" &mdash; job continuity, business, family, property, or a combination.</li>
                        <li>If you're visiting family or friends, know their address, relationship to you and the general shape of your visit.</li>
                    </ul>

                    <h3>What We Help With</h3>
                    <p>Before you submit, we review your documents for the kind of inconsistencies that tend to trigger follow-up questions &mdash; and if UKVI does come back with a request for more information, we help you understand exactly what's being asked and how to respond.</p>
