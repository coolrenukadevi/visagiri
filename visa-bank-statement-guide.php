                <div class="svc-lede" style="text-align:left;max-width:900px;">
                    <h3>What Consulates Are Actually Looking For</h3>
                    <p>A financial document isn't judged only on the closing balance. Reviewing officers are typically looking at three things together:</p>
                    <ul>
                        <li><strong>Sufficiency</strong> &mdash; is there enough to cover the trip (and, for some categories, your stated ongoing expenses back home)?</li>
                        <li><strong>Consistency</strong> &mdash; does the balance look like a normal pattern of income and spending, or a sudden lump-sum deposit right before applying?</li>
                        <li><strong>Traceability</strong> &mdash; can the money be traced to a plausible, legitimate source (salary credits, business income, rent, etc.)?</li>
                    </ul>

                    <h3>How Much Statement History To Include</h3>
                    <p>Most tourist and business visa categories commonly ask for the last 3&ndash;6 months of statements; some categories or destinations ask for more. Check the specific requirement for your destination and category rather than assuming &mdash; we confirm this against the relevant authority's own guidance as part of every application we assist with.</p>

                    <h3>Common Mistakes We See</h3>
                    <ul>
                        <li><strong>A large, unexplained deposit shortly before applying.</strong> If a relative or employer has topped up your account to meet a minimum balance, this is exactly the kind of pattern reviewing officers are trained to notice. If it's genuine (e.g., a bonus, a matured deposit, a legitimate gift), keep the supporting paperwork (gift letter, FD maturity advice, salary slip) ready to explain it.</li>
                        <li><strong>Submitting an unstamped/unsigned printout.</strong> Most consulates want a bank-issued statement with the bank's seal/signature, or a statement downloaded from net banking that clearly shows the account holder's name, account number and bank details on every page &mdash; not just a screenshot.</li>
                        <li><strong>Only showing a savings account when income actually comes through a current/business account.</strong> If you're self-employed or run a business, pair personal statements with your business account and, where relevant, ITR/GST filings so the income story is coherent.</li>
                        <li><strong>Mismatched names.</strong> If the account is a joint account or held by a spouse/parent sponsoring the trip, include a letter clarifying the relationship and confirming the funds are available to you, alongside the account holder's own KYC documents.</li>
                    </ul>

                    <h3>If You're Being Sponsored By Someone Else</h3>
                    <p>Where a family member or employer is sponsoring your trip, most consulates want: the sponsor's own bank statements, a signed sponsorship/undertaking letter, and proof of the sponsor's relationship to you (family record, employment letter, etc.). We help you put this set together correctly rather than submitting statements alone with no explanation.</p>

                    <h3>Self-Employed &amp; Business Owners</h3>
                    <p>Where the applicant runs a business, a stronger financial picture usually combines: business bank statements, ITR filings for the last 2&ndash;3 years, and (where relevant) GST returns or a CA-certified financial statement. A single personal savings account statement, on its own, is usually not enough to represent a business owner's true financial standing.</p>
