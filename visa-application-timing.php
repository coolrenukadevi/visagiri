                <div class="svc-lede" style="text-align:left;max-width:900px;">
                    <h3>General Rule Of Thumb</h3>
                    <ul>
                        <li><strong>Tourist visas:</strong> most processing windows run from a few business days up to a few weeks. We generally suggest applying 4&ndash;6 weeks before travel where possible &mdash; enough buffer for document preparation and any unexpected delay, without applying so early that your documents (like bank statements) feel stale by the time you travel.</li>
                        <li><strong>Business visas:</strong> similar timelines to tourist visas in most cases, though an invitation letter from the host company can take time to arrange &mdash; start that conversation with your host as early as you reasonably can.</li>
                        <li><strong>Family-visit visas:</strong> broadly similar to tourist timelines, but if the visit is tied to a specific date (a wedding, a birth, a medical event), apply as soon as your documents and invitation are ready rather than waiting.</li>
                        <li><strong>Long-stay or category-specific visas</strong> (education-adjacent, employment-linked, etc.): these often carry longer or less predictable processing windows. Start earlier &mdash; several weeks to a few months out, depending on the destination.</li>
                    </ul>

                    <h3>What Can Push Processing Times Out</h3>
                    <ul>
                        <li>Peak seasons &mdash; embassies typically see a surge around major holiday periods, and processing can slow accordingly.</li>
                        <li>An incomplete or inconsistent application, which can trigger a request for more documents (adding real time to the process).</li>
                        <li>Biometric appointment availability, where required &mdash; slots at a Visa Application Centre can book out during busy periods.</li>
                        <li>Additional scrutiny on an individual case, which is at the discretion of the visa-issuing authority and isn't something we (or you) can predict in advance.</li>
                    </ul>

                    <h3>Don't Apply Too Early, Either</h3>
                    <p>Most tourist and business visas aren't meant to be applied for many months ahead of travel &mdash; some destinations set an earliest-submission window (commonly around 3 months before travel, though this varies by country). Financial documents in particular are usually expected to reflect your current situation, so applying too far in advance can mean re-submitting updated statements later.</p>

                    <h3>Our Suggested Timeline</h3>
                    <ol>
                        <li><strong>8&ndash;10 weeks out:</strong> confirm your visa category and destination-specific requirements; start gathering slower-to-obtain documents (invitation letters, NOC letters, etc.).</li>
                        <li><strong>4&ndash;6 weeks out:</strong> finalise and submit your application with current financial documents.</li>
                        <li><strong>2&ndash;3 weeks before travel:</strong> this should be a buffer, not your submission date &mdash; if you're only starting here, you're cutting it closer than we'd recommend for most categories.</li>
                    </ol>
